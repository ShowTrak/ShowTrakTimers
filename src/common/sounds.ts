// Sound references, as stored on a timer and understood by every surface:
//   "builtin:<name>"  one of the sounds bundled with the app (BUILTIN_SOUNDS)
//   "asset:<id>"      a sound imported into the Sound Library (AudioLibrary)
// null means no sound.

export interface BuiltinSound {
  Name: string;
  Label: string;
  /** Path of the file, relative to the UI folder. */
  File: string;
}

export const BUILTIN_SOUNDS: readonly BuiltinSound[] = [
  { Name: 'alert_1', Label: 'Chime', File: 'audio/alert_1.wav' },
  { Name: 'alert_2', Label: 'Alert', File: 'audio/alert_2.wav' },
  { Name: 'alert_3', Label: 'Warning', File: 'audio/alert_3.wav' },
];

// Imported asset ids are generated by AudioLibrary: lowercase hex/uuid-ish.
const ASSET_ID = /^[a-z0-9][a-z0-9-]{0,63}$/;

export type SoundRef = { Kind: 'builtin'; Sound: BuiltinSound } | { Kind: 'asset'; ID: string };

export function ParseSoundRef(Value: unknown): SoundRef | null {
  const Text = String(Value ?? '').trim();
  const Colon = Text.indexOf(':');
  if (Colon <= 0) return null;
  const Kind = Text.slice(0, Colon);
  const Rest = Text.slice(Colon + 1);
  if (Kind === 'builtin') {
    const Sound = BUILTIN_SOUNDS.find((S) => S.Name === Rest);
    return Sound ? { Kind: 'builtin', Sound } : null;
  }
  if (Kind === 'asset' && ASSET_ID.test(Rest)) return { Kind: 'asset', ID: Rest };
  return null;
}

/** A valid sound reference string, or null (no sound) for anything else. */
export function NormalizeSoundRef(Value: unknown): string | null {
  const Ref = ParseSoundRef(Value);
  if (!Ref) return null;
  return Ref.Kind === 'builtin' ? `builtin:${Ref.Sound.Name}` : `asset:${Ref.ID}`;
}

export function BuiltinSoundRef(Name: string): string {
  return `builtin:${Name}`;
}

export function AssetSoundRef(ID: string): string {
  return `asset:${ID}`;
}
